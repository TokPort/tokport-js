// Regenerates the model id lists of both packages from the live catalog:
//   bun scripts/generate-models.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";

type Entry = { id: string; modality: "image" | "video"; status: string; tasks: string[] };

const res = await fetch("https://tokport.io/api/models", { headers: { "user-agent": "tokport-js-codegen" } });
if (!res.ok) throw new Error(`catalog: HTTP ${res.status}`);
const models = ((await res.json()) as { models: Entry[] }).models
  .filter((m) => m.status === "active")
  .sort((a, b) => a.modality.localeCompare(b.modality) || a.id.localeCompare(b.id));
const ids = (pred: (m: Entry) => boolean) => models.filter(pred).map((m) => `  "${m.id}",`).join("\n");
const header = "// Generated by scripts/generate-models.ts from https://tokport.io/api/models. Do not edit.\n";
const root = join(import.meta.dir, "..");

writeFileSync(
  join(root, "packages/client/src/models.ts"),
  `${header}
/** Model ids live when this release was built. Any newer id from https://tokport.io/models works too. */
export const MODEL_IDS = [
${ids(() => true)}
] as const;

export type ModelId = (typeof MODEL_IDS)[number];

/** Modality of each known model; used to pick the sync endpoint. */
export const MODEL_MODALITY: Record<string, "image" | "video"> = {
${models.map((m) => `  "${m.id}": "${m.modality}",`).join("\n")}
};
`,
);

writeFileSync(
  join(root, "packages/ai-sdk-provider/src/model-ids.ts"),
  `${header}
/**
 * Image models that accept reference images (edits). Any other id is accepted
 * through the \`string & {}\` escape hatch. Live list: https://tokport.io/models
 */
export const TOKPORT_IMAGE_EDIT_MODEL_IDS = [
${ids((m) => m.modality === "image" && m.tasks.includes("image-to-image"))}
] as const;

export const TOKPORT_IMAGE_MODEL_IDS = [
${ids((m) => m.modality === "image")}
] as const;

export const TOKPORT_VIDEO_MODEL_IDS = [
${ids((m) => m.modality === "video")}
] as const;

export type TokPortImageModelId = (typeof TOKPORT_IMAGE_MODEL_IDS)[number] | (string & {});

export type TokPortVideoModelId = (typeof TOKPORT_VIDEO_MODEL_IDS)[number] | (string & {});
`,
);
console.log(`wrote ${models.length} models`);
